def _l(title: str, intro: str, points: tuple = (), activity: str | None = None) -> dict:
    parts = [f"<p>{intro}</p>"]
    if points:
        parts.append("<ul>" + "".join(f"<li>{p}</li>" for p in points) + "</ul>")
    if activity:
        parts.append(f"<p><strong>نشاط وتطبيق:</strong> {activity}</p>")
    return {"title": title, "body_html": "".join(parts)}


