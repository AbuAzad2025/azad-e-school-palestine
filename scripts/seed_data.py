def _seed_curriculum(school: School, subject: Subject, grade: Grade, class_room: ClassRoom, teacher: User) -> int:
    """ينشئ الوحدات والدروس الحقيقية لصف واحد. يعيد عدد الدروس."""
    curriculum = CURRICULUM.get(subject.code, {}).get(grade.grade_level)
    if not curriculum:
        return 0

    created = 0
    for order, (unit_title, lessons) in enumerate(curriculum, start=1):
        unit = Unit.query.filter_by(class_id=class_room.id, title=unit_title).first()
        if not unit:

            def _add_unit(unit_title=unit_title, order=order):
                unit = Unit(class_id=class_room.id, title=unit_title, sort_order=order)
                db.session.add(unit)
                db.session.flush()
                return unit

            unit = tx(_add_unit)

        for lorder, lesson in enumerate(lessons, start=1):
            exists = Lesson.query.filter_by(class_id=class_room.id, title=lesson["title"]).first()
            if exists:
                continue

            def _add_lesson(unit=unit, lesson=lesson, lorder=lorder):
                db.session.add(
                    Lesson(
                        class_id=class_room.id,
                        unit_id=unit.id,
                        title=lesson["title"],
                        body_html=lesson["body_html"],
                        sort_order=lorder,
                        status="published",
                        version=1,
                        published_at=db.func.now(),
                        created_by=teacher.id,
                    )
                )

            tx(_add_lesson)
            created += 1
    return created


def _seed_quiz(school, subject, grade, teacher) -> None:
    spec = QUIZZES.get(f"{subject.code}:{grade.grade_level}")
    if not spec:
        return
    class_room = _class_for(school, subject, grade, "first")
    if not class_room:
        return
    existing = Quiz.query.filter_by(class_id=class_room.id, title=spec["title"]).first()
    if existing:
        return

    def _add():
        quiz = Quiz(
            class_id=class_room.id,
            title=spec["title"],
            duration_min=20,
            attempts_allowed=1,
            shuffle=True,
            show_answers_after=True,
            total_mark=sum(float(q["mark"]) for q in spec["questions"]),
            status="published",
            created_by=teacher.id,
        )
        db.session.add(quiz)
        db.session.flush()
        for i, q in enumerate(spec["questions"], start=1):
            db.session.add(
                Question(
                    quiz_id=quiz.id,
                    type=q["type"],
                    prompt=q["prompt"],
                    options=q["options"],
                    correct_answer=q["correct_answer"],
                    mark=q["mark"],
                    sort_order=i,
                )
            )

    tx(_add)
    _out(f"اختبار: {spec['title']}")


def _seed_assignments(school, subject, grade, teacher) -> None:
    specs = ASSIGNMENTS.get(f"{subject.code}:{grade.grade_level}", [])
    class_room = _class_for(school, subject, grade, "first")
