    user = _find_user(email)
    if user:
        _out(f"تخطّي (موجود): {email}")
        return user

    def _add():
        u = User(
            email=email,
            password_hash=hash_password(password),
            role=UserRole(role),
            name_ar=name_ar,
            name_en=name_en,
            locale="ar",
            is_active=True,
            is_verified=verified,
            approval_status=UserApprovalStatus.approved if is_super else UserApprovalStatus.pending,
        )
        db.session.add(u)
        db.session.flush()
